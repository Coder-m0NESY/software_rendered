constexpr int kGlyphW = 5;   // 字形宽（列）
constexpr int kGlyphH = 7;   // 字形高（行）
constexpr int kAdvance = kGlyphW + 1;   // 前进量 = 字形宽 + 1 列字距

// 取字形。表很小（约 50 个），线性找一遍就够了，不值得为它建哈希表。
// 认不出来的一律给 '?'，保证「画出来是个问号」而不是「画出来什么都没有」。
const Glyph& find_glyph(char upper)
{
    for (const Glyph& g : kGlyphs) {
        if (g.c == upper) {
            return g;
        }
    }
    for (const Glyph& g : kGlyphs) {
        if (g.c == '?') {
            return g;
        }
    }
    return kGlyphs[0];
}

