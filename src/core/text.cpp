int line_height(int scale)
{
    if (scale < 1) scale = 1;
    return kGlyphH * scale;
}

int width_of(const std::string& s, int scale)
{
    if (scale < 1) scale = 1;
    return static_cast<int>(s.size()) * kAdvance * scale;
}

void draw(PixelBuffer& fb, int x, int y, const std::string& s,
          const Color& color, int scale)
{
    if (scale < 1) scale = 1;

    int pen = x;
    for (char ch : s) {
        // 小写按大写画：只有一套字形，省一半的表。
        const char upper = static_cast<char>(
            std::toupper(static_cast<unsigned char>(ch)));
        const Glyph& g = find_glyph(upper);

        for (int row = 0; row < kGlyphH; ++row) {
            const uint8_t bits = g.rows[row];
            for (int col = 0; col < kGlyphW; ++col) {
                // bit4 对应最左列，所以要从高位往低位取
                if ((bits >> (kGlyphW - 1 - col)) & 1u) {
                    fb.draw_filled_rect(pen + col * scale, y + row * scale,
                                        scale, scale, color);
                }
            }
        }
        pen += kAdvance * scale;
    }
}

