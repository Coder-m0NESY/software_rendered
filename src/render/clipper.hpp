#ifndef CLIPPER_HPP
#define CLIPPER_HPP

#include "math/vec.hpp"

// ============================================================================
//  clipper ── 近平面裁剪（Sutherland-Hodgman 算法）
//
//  在管线里的位置：「光栅化操作」那一格的第一个子步骤，**在透视除法之前**。
//
//  输入：三角形三个顶点的**裁剪空间**坐标（乘完 MVP 的 (x, y, z, w)）
//  输出：被近平面切过之后剩下的 0 ~ 2 个三角形
//
//  为什么必须在透视除法之前做：
//    透视除法要除以 w，而相机背后的点 w <= 0，除完 x、y 会整块翻号，
//    屏幕上就会出现横穿全屏的「鬼畜三角形」。先裁掉，除法就永远不会炸。
//
//  为什么这里插值天生就是透视正确的（不用像光栅化那样再除 1/w）：
//    裁剪空间坐标是世界坐标的**线性函数**（clip = MVP · p，没有除法）。
//    同一条边上，裁剪空间的插值参数 t 和世界空间的 t 是**同一个**。
//    拿这个 t 去插值顶点属性，得到的就是世界空间里的真值。
//    哪一天你想不通「为什么裁剪不用透视校正」，回来读这三行。
// ============================================================================

// 裁剪空间里的一个顶点：齐次坐标 + 要跟着一起插值的属性。
// 以后要加新属性（法线、颜色…）就往这里加一个成员，裁剪器本身不用改。
struct ClipVertex {
    Vec4  position;         // 裁剪空间 (x, y, z, w)
    Vec2  uv;               // 贴图坐标
    float light = 1.0f;     // 该顶点的亮度 0~1（Lambert 算出来的）
};

namespace clipper {

// 一个三角形切一刀最多变成四边形，四边形扇成 2 个三角形。
constexpr int kMaxOutputTriangles = 2;

// 用近平面裁一个三角形。
//   in     : 三个顶点，绕序无所谓（正面、背面都收）
//   out    : 输出缓冲区，至少要装下 kMaxOutputTriangles * 3 个顶点，紧挨着放
//   返回值 : 输出三角形的个数（0 / 1 / 2）
//
// 「近平面」怎么判：clip.z + clip.w >= 0。
//   投影矩阵把近平面映射到 NDC 的 z = -1，也就是 clip.z = -clip.w，
//   所以 z + w 的符号正好区分「在近平面之前（保留）」和「之后（丢掉）」。
//   对正交投影同样成立（正交时 w 恒为 1，近平面 z = -1 → z + 1 = 0）。
//
// 注意这一版**只裁近平面**：远平面/左右上下四个面不裁。
// 那四个面不裁不会画出穿屏的东西（除以 w 不会炸），只是会多算一些屏幕外的像素，
// 交给光栅化时的包围盒越界判断兜掉就行。完整的六面裁剪留作练习。
int clip_near_plane(const ClipVertex in[3], ClipVertex out[kMaxOutputTriangles * 3]);

}   // namespace clipper

#endif
