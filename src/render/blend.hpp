#ifndef BLEND_HPP
#define BLEND_HPP

#include <cstdint>

#include "core/color.hpp"

// ============================================================================
//  blend ── 第 13 步：两个「片元留不留、留下怎么合成」的开关
//
//  在这之前，光栅化器对每个通过深度测试的片元只有一种处理：直接写进去。
//  但现实里的东西不都是实心的：
//    · 叶片、铁丝网、栅栏 —— 有洞，要么整个像素留下，要么整个丢掉
//        → Alpha 测试（alpha test）
//    · 玻璃、水、半透明贴图 —— 像素要跟后面已经画好的颜色**混一下**
//        → 颜色混合（color blending）
//
//  两者的区别很关键：
//    Alpha 测试：是个「二值开关」，没有中间状态。丢掉的片元**连深度都不写**。
//    颜色混合：片元一定要留下，但留下的方式不是覆盖，而是**算个加权平均**。
//
//  这层不认识 SDL、不认识 Texture，只处理 Color 和 alpha —— 纯逻辑，好测。
// ============================================================================
namespace blend {

// Alpha 测试：这个片元的透明度够不够「实」？
// 返回 true  → 通过，照常画。
// 返回 false → 丢弃：不写颜色、不写深度，等于这个片元从来没来过。
//
// 典型用法是「镂空」：贴图里 alpha = 0 的像素代表洞，
// 把这些片元丢掉之后，模型上就真的出现一个个洞，能看见后面的东西。
// 不丢的话，那些像素会画成一片纯色（甚至黑色），看起来就是一块实心板。
bool alpha_test(uint8_t alpha, uint8_t threshold);

// 颜色混合（over 运算）：把 src 盖到它下面的 dst 上。
//
//     输出 = src × a + dst × (1 - a)        a = alpha / 255
//
// a = 1    → 全是不透明的 src，等价于直接覆盖
// a = 0    → 全是 dst，等于没画
// a = 0.5  → 各占一半，能同时看见 src 和 dst
//
// 这就是最常说的「正常混合 / alpha 混合」。
// 注意它**不可交换**：a 盖 b ≠ b 盖 a。所以半透明物体必须先画远的、
// 后画近的，否则近的被先画的远的混一遍，结果就错了（见 scene 的绘制排序）。
Color blend_over(const Color& src, const Color& dst, uint8_t alpha);

}  // namespace blend

#endif
