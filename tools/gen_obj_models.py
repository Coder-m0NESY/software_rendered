"""生成两个带法线/UV 的 .obj 模型：圆环(torus) 和 球(sphere)。

约定（与 SoftRenderer 一致）：
  - 右手坐标系，Y 轴向上
  - 三角形绕序：cross(B-A, C-A) 指向「物体外侧的反方向」
    （本项目屏幕 y 向下，正面判据 area2 > 0，对应的是「从外面看顺时针」）
  - vt 用标准 OBJ 约定（原点在左下角），由 C++ 加载器负责翻转 v
"""
import math
import os

OUT_DIR = r"d:\SDL_project\softbymyself\assets\models"


def write_obj(path, positions, normals, uvs, tris, comment):
    """tris 里存的是 (pi, ti, ni) 三元组的下标（0 基）。"""
    lines = [f"# {comment}", f"# generated by gen_obj_models.py", ""]
    for p in positions:
        lines.append(f"v {p[0]:.6f} {p[1]:.6f} {p[2]:.6f}")
    lines.append("")
    for t in uvs:
        lines.append(f"vt {t[0]:.6f} {t[1]:.6f}")
    lines.append("")
    for n in normals:
        lines.append(f"vn {n[0]:.6f} {n[1]:.6f} {n[2]:.6f}")
    lines.append("")
    for a, b, c in tris:
        lines.append(
            "f "
            f"{a[0] + 1}/{a[1] + 1}/{a[2] + 1} "
            f"{b[0] + 1}/{b[1] + 1}/{b[2] + 1} "
            f"{c[0] + 1}/{c[1] + 1}/{c[2] + 1}"
        )
    with open(path, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {path}: {len(positions)} verts, {len(tris)} tris")


def fix_winding(a, b, c, positions, outward):
    """保证 cross(B-A, C-A) 与 outward 反向（本项目约定的正面绕序）。"""
    ax, ay, az = positions[a]
    bx, by, bz = positions[b]
    cx, cy, cz = positions[c]
    ux, uy, uz = bx - ax, by - ay, bz - az
    vx, vy, vz = cx - ax, cy - ay, cz - az
    nx = uy * vz - uz * vy
    ny = uz * vx - ux * vz
    nz = ux * vy - uy * vx
    dot = nx * outward[0] + ny * outward[1] + nz * outward[2]
    if dot > 0:          # 与外侧同向 → 需要反过来
        return (a, c, b)
    return (a, b, c)


def gen_torus(major_seg=40, minor_seg=20, R=1.0, r=0.42):
    positions, normals, uvs, tris = [], [], [], []

    # ⚠ 接缝：循环方向的最后一列/行要「重来一次」，让 u/v 能到 1.0。
    #   如果只生成 0..seg-1，最后一列 u=0.975、第一列 u=0.0，它们之间的三角形
    #   会把整张贴图反向采样一遍 —— 表现为模型上一条很明显的暗带。
    #   多生成一圈（位置和第一列重合、但 u=1.0），就变成正常的贴图接缝。
    for i in range(major_seg + 1):
        u = 2.0 * math.pi * (i % major_seg) / major_seg
        cu, su = math.cos(u), math.sin(u)
        for j in range(minor_seg + 1):
            v = 2.0 * math.pi * (j % minor_seg) / minor_seg
            cv, sv = math.cos(v), math.sin(v)
            positions.append(((R + r * cv) * cu, r * sv, (R + r * cv) * su))
            normals.append((cv * cu, sv, cv * su))
            uvs.append((i / major_seg, j / minor_seg))

    stride = minor_seg + 1

    def idx(i, j):
        return i * stride + j

    for i in range(major_seg):
        for j in range(minor_seg):
            a, b = idx(i, j), idx(i, j + 1)
            c, d = idx(i + 1, j + 1), idx(i + 1, j)
            outward = normals[a]
            for tri in ((a, d, b), (b, d, c)):
                t = fix_winding(tri[0], tri[1], tri[2], positions, outward)
                tris.append(((t[0], t[0], t[0]),
                             (t[1], t[1], t[1]),
                             (t[2], t[2], t[2])))
    return positions, normals, uvs, tris


def gen_sphere(seg_u=24, seg_v=16, radius=1.0):
    positions, normals, uvs, tris = [], [], [], []

    for i in range(seg_u + 1):          # 同样多一圈，让 u 能到 1.0（见 torus 的说明）
        phi = 2.0 * math.pi * (i % seg_u) / seg_u
        for j in range(seg_v + 1):
            theta = math.pi * j / seg_v
            st, ct = math.sin(theta), math.cos(theta)
            positions.append((st * math.cos(phi) * radius,
                              ct * radius,
                              st * math.sin(phi) * radius))
            normals.append((st * math.cos(phi), ct, st * math.sin(phi)))
            uvs.append((i / seg_u, 1.0 - j / seg_v))

    stride = seg_v + 1

    def idx(i, j):
        return i * stride + j

    for i in range(seg_u):
        for j in range(seg_v):
            a, b = idx(i, j), idx(i, j + 1)
            c, d = idx(i + 1, j + 1), idx(i + 1, j)
            outward = normals[a]
            for tri in ((a, d, b), (b, d, c)):
                # 极点处的退化三角形直接跳过
                if tri[0] == tri[1] or tri[1] == tri[2] or tri[0] == tri[2]:
                    continue
                t = fix_winding(tri[0], tri[1], tri[2], positions, outward)
                tris.append(((t[0], t[0], t[0]),
                             (t[1], t[1], t[1]),
                             (t[2], t[2], t[2])))
    return positions, normals, uvs, tris


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    p, n, t, f = gen_torus()
    write_obj(os.path.join(OUT_DIR, "torus.obj"), p, n, t, f,
              "torus: parametric donut, smooth normals, full UV")
    p, n, t, f = gen_sphere()
    write_obj(os.path.join(OUT_DIR, "sphere.obj"), p, n, t, f,
              "sphere: UV sphere, smooth normals, full UV")


if __name__ == "__main__":
    main()
